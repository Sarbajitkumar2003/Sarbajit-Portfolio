let toastTimer;
let activeView = "all";

function notify(message) {
    if (!toast) return;
    toast.textContent = message;
    toast.classList.add("show");
    clearTimeout(toastTimer);
    toastTimer = setTimeout(() => toast.classList.remove("show"), 2400);
}

function escapeHTML(value = "") {
    return String(value).replace(/[&<>"']/g, char => ({
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&#39;"
    })[char]);
}

function formatDate(date) {
    const parsed = new Date(date + "T12:00:00");
    if (Number.isNaN(parsed.getTime())) return "Date unavailable";

    return parsed.toLocaleDateString("en-IN", {
        day: "numeric",
        month: "short",
        year: "numeric"
    });
}

// Validate Instagram URLs before using them.
function validInstagramUrl(value) {
    try {
        const url = new URL(value);
        return ["instagram.com", "www.instagram.com", "m.instagram.com"]
            .includes(url.hostname) &&
            /^\/(p|reel|tv)\/[^/]+\/?/.test(url.pathname);
    } catch {
        return false;
    }
}

// Display each project.
function renderProject(project) {
    let media;

    if (project.type === "photo") {
        media = `
            <img
                src="${escapeHTML(project.image)}"
                alt="${escapeHTML(project.title)}"
                loading="lazy"
                onerror="this.style.display='none';
                         this.parentElement.classList.add('media-missing');"
            >
        `;
    } else {
        const reelUrl = validInstagramUrl(project.instagramUrl)
            ? project.instagramUrl
            : "https://www.instagram.com/";

        media = `
            <a
                class="instagram-cover"
                href="${escapeHTML(reelUrl)}"
                target="_blank"
                rel="noopener noreferrer"
                aria-label="Open ${escapeHTML(project.title)} on Instagram"
            >
                <img
                    class="instagram-thumbnail"
                    src="${escapeHTML(project.cover || "")}"
                    alt="${escapeHTML(project.title)}"
                    loading="lazy"
                    onerror="this.style.display='none';"
                >
                <span class="instagram-play">▶</span>
                <span class="instagram-label">
                    View Reel on Instagram ↗
                </span>
            </a>
        `;
    }

    const promptSection = project.type === "photo" && project.prompt
        ? `
            <span class="prompt-label">✨ AI CREATION PROMPT</span>
            <div class="prompt-text">${escapeHTML(project.prompt)}</div>

            <div class="project-actions">
                <button class="action-btn copy"
                    data-action="copy" data-id="${project.id}">
                    📋 Copy Prompt
                </button>

                <button class="action-btn"
                    data-action="chatgpt" data-id="${project.id}">
                    🤖 Create with ChatGPT
                </button>

                <button class="action-btn"
                    data-action="gemini" data-id="${project.id}">
                    ✨ Create with Gemini
                </button>
            </div>
        `
        : "";

    return `
        <article class="project-card">
            <div class="project-media">${media}</div>

            <div class="project-content">
                <div class="project-top">
                    <h3>${escapeHTML(project.title)}</h3>
                </div>

                <p class="project-date">
                    Uploaded: ${escapeHTML(formatDate(project.date))}
                </p>

                <p class="project-description">
                    ${escapeHTML(project.description || "")}
                </p>

                ${promptSection}
            </div>
        </article>
    `;
}

function renderProjects() {
    if (!photoContainer || !videoContainer) return;

    const search = searchInput?.value.trim().toLowerCase() || "";
    const sort = sortSelect?.value || "newest";

    const filtered = projects.filter(project => {
        const matchesView =
            activeView === "all" || project.type === activeView;

        const content = [
            project.title,
            project.description,
            project.prompt,
            project.type,
            project.instagramUrl
        ].join(" ").toLowerCase();

        return matchesView && content.includes(search);
    });

    filtered.sort((a, b) => {
        if (sort === "oldest") return a.date.localeCompare(b.date);
        if (sort === "az") return a.title.localeCompare(b.title);
        return b.date.localeCompare(a.date);
    });

    const photos = filtered.filter(p => p.type === "photo");
    const videos = filtered.filter(p => p.type === "video");

    photoContainer.innerHTML = photos.length
        ? photos.map(renderProject).join("")
        : '<p class="empty-state">No photo projects found.</p>';

    videoContainer.innerHTML = videos.length
        ? videos.map(renderProject).join("")
        : '<p class="empty-state">No video projects found.</p>';

    const photoCount = document.getElementById("photoCount");
    const videoCount = document.getElementById("videoCount");

    if (photoCount) {
        photoCount.textContent =
            `${photos.length} ${photos.length === 1 ? "project" : "projects"}`;
    }

    if (videoCount) {
        videoCount.textContent =
            `${videos.length} ${videos.length === 1 ? "project" : "projects"}`;
    }

    photoSection?.classList.toggle("is-hidden", activeView === "video");
    videoSection?.classList.toggle("is-hidden", activeView === "photo");
    categoryGrid?.classList.toggle("single-view", activeView !== "all");

    if (viewStatus) {
        viewStatus.textContent = activeView === "photo"
            ? "Showing photo editing projects only"
            : activeView === "video"
                ? "Showing video editing projects only"
                : "Showing all projects";
    }

    document.querySelectorAll(".nav-item").forEach(link => {
        const active = link.dataset.view === activeView;
        link.classList.toggle("active", active);

        if (active) link.setAttribute("aria-current", "page");
        else link.removeAttribute("aria-current");
    });
}

function setView(view) {
    activeView = view;
    renderProjects();

    navbar?.classList.remove("open");
    menuToggle?.setAttribute("aria-expanded", "false");

    const target = view === "photo"
        ? photoSection
        : view === "video"
            ? videoSection
            : document.getElementById("all-projects");

    history.replaceState(
        null,
        "",
        view === "all" ? "#all-projects" : `#${target?.id || ""}`
    );

    target?.scrollIntoView({ behavior: "smooth", block: "start" });
}

document.querySelectorAll(".nav-item").forEach(link => {
    link.addEventListener("click", event => {
        event.preventDefault();
        setView(link.dataset.view || "all");
    });
});

menuToggle?.addEventListener("click", () => {
    const open = navbar?.classList.toggle("open") || false;

    menuToggle.setAttribute("aria-expanded", String(open));
    menuToggle.setAttribute(
        "aria-label",
        open ? "Close navigation" : "Open navigation"
    );
    menuToggle.textContent = open ? "✕" : "☰";
});

async function copyPrompt(prompt) {
    try {
        await navigator.clipboard.writeText(prompt);
        return true;
    } catch {
        const area = document.createElement("textarea");
        area.value = prompt;
        area.style.position = "fixed";
        area.style.opacity = "0";
        document.body.appendChild(area);
        area.select();

        let success = false;
        try {
            success = document.execCommand("copy");
        } catch {}

        area.remove();
        return success;
    }
}

document.addEventListener("click", async event => {
    const button = event.target.closest("button[data-action]");
    if (!button) return;

    const project = projects.find(
        item => String(item.id) === button.dataset.id
    );
    if (!project) return;

    const action = button.dataset.action;

    if (action === "copy") {
        const success = await copyPrompt(project.prompt || "");
        notify(success ? "✅ Prompt copied!" : "Copy failed.");
        return;
    }

    const url = action === "chatgpt"
        ? "https://chatgpt.com/"
        : "https://gemini.google.com/";

    window.open(url, "_blank", "noopener,noreferrer");

    const success = await copyPrompt(project.prompt || "");
    notify(success
        ? "Prompt copied! Paste it into the AI chat."
        : "Copy the prompt from your project card.");
});

searchInput?.addEventListener("input", renderProjects);
sortSelect?.addEventListener("change", renderProjects);

window.addEventListener("scroll", () => {
    const bar = document.getElementById("progressBar");
    if (!bar) return;

    const total = document.documentElement.scrollHeight - window.innerHeight;
    bar.style.width =
        `${total > 0 ? (window.scrollY / total) * 100 : 0}%`;
});

function applyHashView() {
    if (location.hash === "#photo-section") activeView = "photo";
    else if (location.hash === "#video-section") activeView = "video";
    else activeView = "all";

    renderProjects();
}

window.addEventListener("hashchange", applyHashView);
applyHashView();
